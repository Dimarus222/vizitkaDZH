#!/usr/bin/env python3
"""
Генератор сид-данных для 100 карточек проектов (лендинги / одностраничники / многостраничные сайты).
Запускается один раз при разработке, чтобы наполнить projects.seed.json.
Каждая карточка — это витрина-описание шаблона с уникальной комбинацией:
категории, ниши, набора опций (форма заявки, обратная связь, калькулятор и т.д.),
цветовой темы и технологического стека.

Важно: это НЕ 100 вручную сверстанных уникальных сайтов (это нереально уместить
в одну выгрузку), а система из 100 УНИКАЛЬНЫХ карточек-описаний с разными
параметрами, которые рендерятся через общий адаптивный шаблон превью на сайте.
Через админ-панель каждую карточку можно заменить на карточку реального
готового проекта (со своей ссылкой, скриншотом и описанием), когда появится 100
реальных работ.
"""
import json
import random

random.seed(42)

categories = [
    "Лендинг", "Одностраничный сайт", "Многостраничный сайт",
    "Интернет-магазин", "Корпоративный сайт", "Промо-сайт",
]

niches = [
    "Стоматологическая клиника", "Автосервис", "Юридическая компания",
    "Фитнес-клуб", "Ресторан доставки", "Салон красоты", "Строительная фирма",
    "IT-стартап", "Курсы английского", "Фотограф", "Дизайн интерьера",
    "Кофейня", "Барбершоп", "Агентство недвижимости", "Event-агентство",
    "Логистическая компания", "Клининговая компания", "Питомник растений",
    "Ветеринарная клиника", "Турагентство", "Автошкола", "Медицинский центр",
    "Производство мебели", "Веб-студия", "Маркетинговое агентство",
    "Финансовый консалтинг", "Страховая компания", "Спортивная школа",
    "Детский центр развития", "Швейное ателье", "Пекарня", "Цветочный магазин",
    "Тату-студия", "Йога-студия", "Автомойка", "Служба такси",
    "Мастерская по ремонту техники", "Онлайн-школа программирования",
    "Консалтинг по недвижимости", "Ювелирный бренд", "Магазин электроники",
    "Производитель косметики", "Компания по грузоперевозкам",
    "Архитектурное бюро", "Студия звукозаписи", "Издательство",
    "Сельхозпроизводитель", "Компания по установке окон", "Клиника эстетической медицины",
    "Барный проект", "Кальянная",
]

features_pool = [
    "форма обратной связи", "форма заявки", "онлайн-калькулятор стоимости",
    "запись на приём/услугу", "каталог товаров/услуг с фильтрами",
    "интеграция с CRM", "онлайн-оплата", "чат/виджет мессенджера",
    "мультиязычность", "блог/новости", "карта с адресами филиалов",
    "личный кабинет", "квиз-опрос перед заявкой", "галерея работ/портфолио",
    "отзывы клиентов", "всплывающие акции/попапы",
]

tech_options = [
    ["HTML", "CSS", "JS"],
    ["HTML", "CSS", "JS", "PHP"],
    ["React", "Node.js"],
    ["Go", "HTML", "CSS", "JS"],
    ["Python (Flask)", "HTML", "CSS", "JS"],
    ["Vue", "Node.js"],
    ["HTML", "Tailwind CSS", "JS"],
]

color_themes = ["cyber-green", "cyber-blue", "cyber-purple", "cyber-red", "cyber-amber"]

adjectives = ["Премиум", "Минимал", "Экспресс", "Флагман", "Стандарт", "Индивидуальный"]

projects = []
used_titles = set()

for i in range(1, 101):
    niche = niches[(i - 1) % len(niches)]
    category = categories[i % len(categories)]
    adj = adjectives[i % len(adjectives)]
    title = f"{adj}-{category.split()[0].lower()} «{niche}»"
    # гарантируем уникальность заголовка
    suffix = 1
    base_title = title
    while title in used_titles:
        suffix += 1
        title = f"{base_title} #{suffix}"
    used_titles.add(title)

    n_features = random.choice([3, 4, 5])
    features = random.sample(features_pool, n_features)
    tech = random.choice(tech_options)
    theme = color_themes[i % len(color_themes)]

    description = (
        f"{category} для ниши «{niche.lower()}». "
        f"Реализован адаптивный дизайн под все устройства, ускоренная загрузка "
        f"и базовая защита от типовых уязвимостей (XSS, CSRF, валидация форм)."
    )

    projects.append({
        "id": i,
        "title": title,
        "category": category,
        "niche": niche,
        "description": description,
        "features": features,
        "tech": tech,
        "theme": theme,
        "demo_url": "",
        "image": "",
        "secure": True,
    })

with open("projects.seed.json", "w", encoding="utf-8") as f:
    json.dump(projects, f, ensure_ascii=False, indent=2)

print(f"Сгенерировано {len(projects)} карточек в projects.seed.json")
